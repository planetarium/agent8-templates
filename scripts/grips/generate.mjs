#!/usr/bin/env node

// Builds the weapon grip table the R3F templates' hold part reads by weapon URL
// (basic-3d-freeview/src/game/grips.json; `npm run 3d:sync` copies it to the others).
//
// Source of truth: agent8-library metadata `grip` (kind, point, forward, up, lengthM, and
// muzzleTip when present) in assets/3d/weapons, objects/weapons melee and objects/weapons ranged.
// scripts/grips/measured.json adds values measured from the vertices for weapons the library has
// no grip for yet; a library value wins over a measured one.
//
//   node scripts/grips/generate.mjs <agent8-library checkout>          write grips.json
//   node scripts/grips/generate.mjs <agent8-library checkout> --check  exit 1 if it would change

import { existsSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const OUT = join(ROOT, 'basic-3d-freeview', 'src', 'game', 'grips.json');
const FOLDERS = ['weapons', 'objects/weapons melee', 'objects/weapons ranged'];
const FIELDS = ['kind', 'point', 'forward', 'up', 'lengthM', 'muzzleTip'];

const args = process.argv.slice(2);
const check = args.includes('--check');
const lib = args.find((a) => !a.startsWith('--'));
if (!lib) {
  console.log('usage: node scripts/grips/generate.mjs <agent8-library checkout> [--check]');
  process.exit(1);
}

const pick = (g) => Object.fromEntries(FIELDS.filter((f) => g[f] !== undefined).map((f) => [f, g[f]]));
const grips = {};
for (const [key, g] of Object.entries(JSON.parse(readFileSync(join(HERE, 'measured.json'), 'utf8')))) grips[key] = pick(g);

let fromLibrary = 0;
for (const folder of FOLDERS) {
  const file = join(lib, 'assets', '3d', folder, 'metadata.json');
  if (!existsSync(file)) {
    console.log(`missing ${file}`);
    process.exit(1);
  }
  for (const [name, entry] of Object.entries(JSON.parse(readFileSync(file, 'utf8')))) {
    const g = entry && typeof entry === 'object' ? entry.metadata?.grip : undefined;
    if (!g) continue;
    grips[`${folder}/${name}`.toLowerCase()] = pick(g);
    fromLibrary++;
  }
}

const keys = Object.keys(grips).sort();
const lines = keys.map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(grips[k])}`);
const text = `{\n  "source": "agent8-library metadata grip (${FOLDERS.join(', ')}) + scripts/grips/measured.json — generated by scripts/grips/generate.mjs, do not edit",\n  "grips": {\n${lines.join(',\n')}\n  }\n}\n`;

const lf = (s) => s.replace(/\r\n/g, '\n');
if (check) {
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (lf(have) !== text) {
    console.log('grips.json differs from the library + measured values. Run node scripts/grips/generate.mjs <library>.');
    process.exit(1);
  }
  console.log(`grips.json up to date (${keys.length} weapons).`);
} else {
  writeFileSync(OUT, text);
  console.log(`grips.json: ${keys.length} weapons (${fromLibrary} from the library, ${keys.length - fromLibrary} measured only).`);
}
